import { isAbsolute, resolve } from "node:path";
import { buildCheckEnv } from "../verification/check-runner.js";
import { WorkflowFault } from "./errors.js";
import type { Check } from "./types.js";

/**
 * A required check whose executable cannot be started is a deterministic environment failure:
 * running on only spends tokens (R8 propdrift b9a571b0 kept implementing for 400k tokens after
 * `mvn` first failed with `spawn_error`). The first such result stops the run.
 */
export function failFastUnavailable(
  check: Pick<Check, "id" | "required" | "executable" | "args">,
  result: { reason?: string; output?: string },
): void {
  if (!check.required || result.reason !== "spawn_error") return;
  throw new WorkflowFault(
    "OUTPUT_INVALID",
    `Required check ${check.id} cannot be started: ${[check.executable, ...check.args].join(" ")} (${(result.output ?? "").split("\n")[0]}). Install the tool or fix the check, then resume.`,
    { reason: "check_unavailable", checkId: check.id, executable: check.executable },
  );
}

export interface CheckProbe {
  checkId: string;
  executable: string;
  required: boolean;
}

/**
 * Start-time smoke of the declared checks: every check whose executable is a bare command name
 * must resolve on the PATH the check would run with (`PATHEXT` included on Windows). A path
 * (`./gradlew`) may be generated by a task and is not probed; `bun` is the running binary.
 */
export function unresolvedChecks(
  checks: readonly Check[],
  root: string,
  which: (command: string, options: { PATH: string; cwd: string }) => string | null = (
    command,
    options,
  ) => Bun.which(command, options),
): CheckProbe[] {
  const missing: CheckProbe[] = [];
  for (const check of checks) {
    const executable = check.executable;
    if (executable === "bun" || /[/]/.test(executable) || isAbsolute(executable)) continue;
    const env = buildCheckEnv(check);
    const cwd = check.cwd === "." ? root : resolve(root, check.cwd);
    const path = env.PATH ?? env.Path ?? "";
    if (!which(executable, { PATH: path, cwd }))
      missing.push({ checkId: check.id, executable, required: check.required });
  }
  return missing;
}

import {
  FEATURES,
  type Feature,
  GROUPS,
  issueOf,
  SURFACE_LABELS,
  SURFACES,
  type SurfaceEntry,
  targetOf,
} from "./registry.js";

export const PARITY_START = "<!-- parity:start (generated by bun scripts/parity-docs.ts) -->";
export const PARITY_END = "<!-- parity:end -->";

const ISSUES = "https://github.com/Gulliby-development/baked/issues";
const issueLink = (n: number): string => `[#${n}](${ISSUES}/${n})`;

function cell(entry: SurfaceEntry): string {
  if (Array.isArray(entry)) {
    const targets = [...new Set(entry.map(targetOf))];
    const shown = targets.slice(0, 3).map((t) => `\`${t}\``);
    return targets.length > 3 ? `${shown.join(", ")} +${targets.length - 3}` : shown.join(", ");
  }
  const e = entry as Exclude<SurfaceEntry, readonly string[]>;
  switch (e.status) {
    case "gap":
      return `**Gap** ${issueLink(e.issue)}${e.note ? `: ${e.note}` : ""}`;
    case "partial":
      return `Partial ${issueLink(e.issue)}: ${e.note}`;
    case "terminal-only":
      return `Terminal only: ${e.reason}`;
    case "desktop-only":
      return `Desktop only: ${e.reason}`;
    case "not-needed":
      return `Not needed: ${e.reason}`;
  }
}

/** The generated part of `docs/parity.md`: one table per group and the open gaps by issue. */
export function renderParity(features: readonly Feature[] = FEATURES): string {
  const lines: string[] = [];
  for (const group of GROUPS) {
    const rows = features.filter((f) => f.group === group);
    if (rows.length === 0) continue;
    lines.push(`### ${group}`, "");
    lines.push(`| Feature | ${SURFACES.map((s) => SURFACE_LABELS[s]).join(" | ")} |`);
    lines.push(`| --- | ${SURFACES.map(() => "---").join(" | ")} |`);
    for (const f of rows)
      lines.push(`| ${f.title} | ${SURFACES.map((s) => cell(f[s])).join(" | ")} |`);
    lines.push("");
  }
  const byIssue = new Map<number, Set<string>>();
  for (const f of features)
    for (const s of SURFACES) {
      const issue = issueOf(f[s]);
      if (issue === null) continue;
      const set = byIssue.get(issue) ?? new Set<string>();
      set.add(f.title);
      byIssue.set(issue, set);
    }
  lines.push("### Open gaps by issue", "");
  for (const [issue, titles] of [...byIssue].sort((a, b) => a[0] - b[0]))
    lines.push(`- ${issueLink(issue)}: ${[...titles].join("; ")}`);
  return lines.join("\n");
}

/** `markdown` with the text between the parity markers replaced by `renderParity()`. */
export function withParityTable(markdown: string): string {
  const start = markdown.indexOf(PARITY_START);
  const end = markdown.indexOf(PARITY_END);
  if (start === -1 || end < start) throw new Error("docs/parity.md has no parity markers");
  return `${markdown.slice(0, start + PARITY_START.length)}\n\n${renderParity()}\n\n${markdown.slice(end)}`;
}

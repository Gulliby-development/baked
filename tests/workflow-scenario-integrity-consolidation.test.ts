import { describe, expect, test } from "bun:test";
import { consolidateTargets, scanTestIntegrity } from "../src/core/workflows/test-integrity.js";

// #2467, R79 deltaglue chunks: T002's tests built their inputs by interpolation where the brief
// asked for literal rows. Review finding F1 ("The tests construct inputs and expected results
// rather than using the required literal object rows") sent corrective T003, which merged 10
// generated tests into 5 literal-table tests (66 assertions to 64). The guard's `test-count` rule
// blocked it as 5 removed tests, and T004 restored the generated tests: 8.28M tokens and two
// `attempt_cap` stops. A correction whose spec finding asks for literal rows may now merge tests
// while the file still declares a test and keeps nine tenths of its assertions.

const F1 = "The tests construct inputs and expected results rather than using the required literal object rows";
const finding = (claim: string, extra: { file?: string; basis?: string; kind?: string } = {}) => ({
  kind: extra.kind ?? "correctness",
  file: extra.file ?? "tests/chunks.test.ts",
  claim,
  suggestedFix: "Correct the tests",
  ...(extra.basis ? { basis: extra.basis } : {}),
});

describe("the files a correction's finding asks to build from literal rows (#2467)", () => {
  test("a spec finding about generated inputs or literal rows qualifies its test file", () => {
    expect([...consolidateTargets([finding(F1)])]).toEqual(["tests/chunks.test.ts"]);
    expect([...consolidateTargets([finding("chunks.test.ts interpolates its inputs instead of literal rows")])]).toEqual(["tests/chunks.test.ts"]);
    expect([...consolidateTargets([finding("The cases are generated by a loop; use a table-driven test", { file: "tests/test_chunks.py" })])]).toEqual(["tests/test_chunks.py"]);
  });

  test("an inferred finding, a source file, another claim and the guard's own finding do not", () => {
    expect([...consolidateTargets([finding(F1, { basis: "inferred" })])]).toEqual([]);
    expect([...consolidateTargets([finding(F1, { file: "src/chunks.ts" })])]).toEqual([]);
    expect([...consolidateTargets([finding("chunks.test.ts asserts the wrong surrogate")])]).toEqual([]);
    expect([...consolidateTargets([finding("Test integrity (test-count): task T003 test count dropped from 10 to 5")])]).toEqual([]);
  });
});

/** Per language: ten generated tests before, and the same cases as literal tables after. */
const LANGUAGES: Record<string, { path: string; generated: string; literal: string; empty: string }> = {
  typescript: {
    path: "tests/chunks.test.ts",
    generated: Array.from({ length: 10 }, (_, i) => `test("case ${i}", () => {\n  const input = \`row-\${${i}}\`;\n  expect(chunk(input)).toBe(\`row-\${${i}}\`);\n  expect(size(input)).toBe(${i});\n});\n`).join(""),
    literal: Array.from({ length: 5 }, (_, t) => `test("table ${t}", () => {\n  for (const [input, out, n] of [["row-${2 * t}", "row-${2 * t}", ${2 * t}], ["row-${2 * t + 1}", "row-${2 * t + 1}", ${2 * t + 1}]] as const) {\n    expect(chunk(input)).toBe(out);\n    expect(size(input)).toBe(n);\n  }\n  expect(chunk("")).toBe("");\n  expect(size("")).toBe(0);\n});\n`).join(""),
    empty: "// no tests\n",
  },
  python: {
    path: "tests/test_chunks.py",
    generated: Array.from({ length: 10 }, (_, i) => `def test_case_${i}():\n    value = f"row-{${i}}"\n    assert chunk(value) == f"row-{${i}}"\n    assert size(value) == ${i}\n\n`).join(""),
    literal: Array.from({ length: 5 }, (_, t) => `def test_table_${t}():\n    for value, out, n in [("row-${2 * t}", "row-${2 * t}", ${2 * t}), ("row-${2 * t + 1}", "row-${2 * t + 1}", ${2 * t + 1})]:\n        assert chunk(value) == out\n        assert size(value) == n\n    assert chunk("") == ""\n    assert size("") == 0\n\n`).join(""),
    empty: "# no tests\n",
  },
  go: {
    path: "chunks_test.go",
    generated: `package chunks\n\nimport "testing"\n\n${Array.from({ length: 10 }, (_, i) => `func TestCase${i}(t *testing.T) {\n\tin := fmt.Sprintf("row-%d", ${i})\n\tif Chunk(in) != in {\n\t\tt.Errorf("chunk")\n\t}\n\tif Size(in) != ${i} {\n\t\tt.Errorf("size")\n\t}\n}\n`).join("")}`,
    literal: `package chunks\n\nimport "testing"\n\n${Array.from({ length: 5 }, (_, t) => `func TestTable${t}(t *testing.T) {\n\tfor _, c := range []struct{ in string; n int }{{"row-${2 * t}", ${2 * t}}, {"row-${2 * t + 1}", ${2 * t + 1}}} {\n\t\tif Chunk(c.in) != c.in {\n\t\t\tt.Errorf("chunk")\n\t\t}\n\t\tif Size(c.in) != c.n {\n\t\t\tt.Errorf("size")\n\t\t}\n\t}\n\tif Chunk("") != "" {\n\t\tt.Errorf("empty chunk")\n\t}\n\tif Size("") != 0 {\n\t\tt.Errorf("empty size")\n\t}\n}\n`).join("")}`,
    empty: "package chunks\n",
  },
};

describe("scenario: R79 deltaglue chunks T003, ten generated tests merged into five literal tables (#2467)", () => {
  for (const [language, { path, generated, literal, empty }] of Object.entries(LANGUAGES))
    test(`${language}: the merge the finding asks for passes; without the finding it is a removal`, () => {
      const scan = (after: string, consolidates: string[]) =>
        scanTestIntegrity([{ path, before: generated, after }], { consolidates: new Set(consolidates) }).map((f) => f.rule);
      expect(scan(literal, [path])).toEqual([]);
      // The same merge without the finding, or with the finding on another file, still blocks.
      expect(scan(literal, [])).toContain("test-count");
      expect(scan(literal, ["other.test.ts"])).toContain("test-count");
      // A file left without tests, or with most of its assertions gone, is no consolidation.
      expect(scan(empty, [path])).toContain("test-count");
      const halved = literal.split("\n").filter((line) => !/size/i.test(line)).join("\n");
      expect(scan(halved, [path])).toContain("assertions");
    });
});
